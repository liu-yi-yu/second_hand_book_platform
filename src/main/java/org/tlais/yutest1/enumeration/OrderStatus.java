package org.tlais.yutest1.enumeration;

/**
 * 订单状态枚举
 */
public enum OrderStatus {

    /**
     * 待确认
     */
    PENDING,

    /**
     * 已确认
     */
    CONFIRMED,

    /**
     * 已发货
     */
    SHIPPED,

    /**
     * 已收货
     */
    RECEIVED,

    /**
     * 已完成
     */
    COMPLETED,

    /**
     * 已取消
     */
    CANCELLED

}
